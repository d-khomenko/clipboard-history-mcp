use anyhow::{anyhow, Result};
use arboard::Clipboard;
use std::sync::Mutex;

static CLIPBOARD: once_cell::sync::Lazy<Mutex<Clipboard>> = once_cell::sync::Lazy::new(|| {
    Mutex::new(Clipboard::new().expect("init system clipboard"))
});

pub fn read_clipboard() -> Result<String> {
    let mut cb = CLIPBOARD.lock().map_err(|_| anyhow!("clipboard mutex poisoned"))?;
    match cb.get_text() {
        Ok(s) => Ok(s),
        Err(arboard::Error::ContentNotAvailable) => Ok(String::new()),
        Err(e) => Err(anyhow!("clipboard read: {}", e)),
    }
}

pub fn write_clipboard(text: &str) -> Result<()> {
    let mut cb = CLIPBOARD.lock().map_err(|_| anyhow!("clipboard mutex poisoned"))?;
    cb.set_text(text.to_string()).map_err(|e| anyhow!("clipboard write: {}", e))?;
    Ok(())
}

/// Returns `true` if the current pasteboard carries a "concealed" UTI
/// (org.nspasteboard.ConcealedType / AutoGeneratedType /
/// com.apple.is-sensitive). On macOS this queries NSPasteboard via
/// `objc2-app-kit`. Other platforms return `false`; CLIPBOARD_IGNORE_APPS
/// is the cross-platform compensation mechanism.
pub fn is_transient() -> bool {
    #[cfg(target_os = "macos")]
    {
        macos_pb::is_transient_macos()
    }
    #[cfg(not(target_os = "macos"))]
    {
        false
    }
}

/// Best-effort change counter for change-detection. arboard does not expose
/// the underlying changeCount; we hash-compare the text instead in the
/// watcher tick. This function exists for backward API compatibility and
/// just returns the current Unix epoch ms — the watcher does not actually
/// rely on monotonicity.
pub fn change_count() -> i64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or_default().as_millis() as i64
}

#[cfg(target_os = "macos")]
mod macos_pb {
    use objc2::rc::autoreleasepool;
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::NSString;

    /// Pasteboard type UTIs that signal "do not record" by community or
    /// Apple convention.
    const CONCEALED_UTIS: &[&str] = &[
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.apple.is-sensitive",
    ];

    pub fn is_transient_macos() -> bool {
        autoreleasepool(|_| {
            let pb = NSPasteboard::generalPasteboard();
            let Some(types) = pb.types() else {
                return false;
            };
            for uti in CONCEALED_UTIS {
                let needle = NSString::from_str(uti);
                if types.containsObject(&needle) {
                    return true;
                }
            }
            false
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[ignore] // requires real clipboard
    fn round_trip() {
        write_clipboard("hello pasteboard").unwrap();
        let got = read_clipboard().unwrap();
        assert_eq!(got, "hello pasteboard");
    }

    #[test]
    #[cfg(not(target_os = "macos"))]
    fn is_transient_false_on_non_macos() {
        // Linux / Windows / etc. have no NSPasteboard; the fallback must be
        // false so the watcher does not silently skip every clip.
        assert!(!is_transient());
    }
}
